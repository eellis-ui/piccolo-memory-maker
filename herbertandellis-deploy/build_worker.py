#!/usr/bin/env python3
"""Pack the herbertandellis/ site into a single Cloudflare Pages worker.

Usage: build_worker.py <site dir> <output dir>

Writes <output dir>/_worker.js, which holds every file of the site and serves
them the way Cloudflare Pages serves static files (clean URLs, a 404 page,
ETags). Deploy the output dir with:
  wrangler pages deploy <output dir> --project-name=herbert-ellis --branch=main --skip-caching
It needs only a Cloudflare API token, which is why it exists: uploading the
files as ordinary static assets is not possible from every environment.
"""
import base64, hashlib, json, os, sys

TYPES = {'.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'application/javascript',
         '.png': 'image/png', '.xml': 'application/xml', '.txt': 'text/plain; charset=utf-8',
         '.svg': 'image/svg+xml', '.jpg': 'image/jpeg', '.ico': 'image/x-icon', '.json': 'application/json'}
SKIP = {'README.md', 'README.txt'}

def main(site, out):
    files = {}
    for root, _, names in os.walk(site):
        for n in sorted(names):
            if n in SKIP or n.startswith('.'):
                continue
            p = os.path.join(root, n)
            rel = '/' + os.path.relpath(p, site).replace(os.sep, '/')
            data = open(p, 'rb').read()
            files[rel] = {'t': TYPES[os.path.splitext(n)[1].lower()], 'e': '"' + hashlib.sha1(data).hexdigest()[:32] + '"',
                          'b': base64.b64encode(data).decode()}
    assert '/index.html' in files and '/404.html' in files
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, '_worker.js'), 'w').write(WORKER.replace('__FILES__', json.dumps(files, sort_keys=True)))
    print(len(files), 'files packed')

WORKER = r'''// Generated by herbertandellis-deploy/build_worker.py. Do not edit: rebuild from the herbertandellis/ folder.
const FILES = __FILES__;
const LIVE_HOST = "www.herbertandellis.com";
const cache = new Map();
function body(path) {
  let b = cache.get(path);
  if (!b) { const s = atob(FILES[path].b); b = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i); cache.set(path, b); }
  return b;
}
function serve(req, url, path, status) {
  const f = FILES[path];
  const h = new Headers({
    "content-type": f.t, "etag": f.e,
    "cache-control": f.t.startsWith("image/") ? "public, max-age=86400" : "public, max-age=0, must-revalidate",
    "access-control-allow-origin": "*", "referrer-policy": "strict-origin-when-cross-origin", "x-content-type-options": "nosniff",
  });
  if (url.hostname !== LIVE_HOST) h.set("x-robots-tag", "noindex");
  if (status === 200 && req.headers.get("if-none-match") === f.e) return new Response(null, { status: 304, headers: h });
  return new Response(req.method === "HEAD" ? null : body(path), { status, headers: h });
}
function redirect(url, to) { return new Response(null, { status: 308, headers: { location: to + url.search } }); }
export default {
  async fetch(req) {
    if (req.method !== "GET" && req.method !== "HEAD") return new Response("Method not allowed", { status: 405, headers: { allow: "GET, HEAD" } });
    const url = new URL(req.url);
    let p; try { p = decodeURIComponent(url.pathname); } catch (e) { p = url.pathname; }
    // Clean URLs, as Cloudflare Pages serves them
    if (p.endsWith("/index.html")) return redirect(url, p.slice(0, -10));
    if (p.endsWith(".html") && FILES[p]) return redirect(url, p.slice(0, -5));
    if (p.endsWith("/")) { if (FILES[p + "index.html"]) return serve(req, url, p + "index.html", 200); }
    else {
      if (FILES[p]) return serve(req, url, p, 200);
      if (FILES[p + "/index.html"]) return redirect(url, p + "/");
      if (FILES[p + ".html"]) return serve(req, url, p + ".html", 200);
    }
    return serve(req, url, "/404.html", 404);
  },
};
'''

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
